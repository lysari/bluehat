    @Test func readsEveryLockfileOfEachProjectAndSkipsOversizedOnes() throws {
        defer { try? FileManager.default.removeItem(at: root) }
        try write("{}", to: "app/package.json")
        try write(Self.packageLockV3, to: "app/package-lock.json")
        try write(Self.yarnClassic, to: "app/yarn.lock")
        try write(Self.pnpmV9, to: "lib/pnpm-lock.yaml")
        try write(Self.pnpmV9, to: "no-manifest/pnpm-lock.yaml")
        try write("{}", to: "huge/package.json")
        FileManager.default.createFile(atPath: root.appending(path: "huge/package-lock.json").path, contents: nil)
        let huge = try FileHandle(forWritingTo: root.appending(path: "huge/package-lock.json"))
        try huge.truncate(atOffset: UInt64(NpmInventory.maxLockfileBytes + 1))
        try huge.close()
        try write("{}", to: "lib/package.json")
        let projects = ProjectFolders.directories(in: [root.path], containing: NpmInventory.projectFileNames).directories

        let inventory = NpmInventory.packages(inProjects: projects, moduleDirectories: [])

        let summary = inventory.packages.map { "\($0.path.replacingOccurrences(of: root.path + "/", with: "")) \($0.name)@\($0.version)" }
        #expect(summary == [
            "app/package-lock.json @babel/core@7.24.0",
            "app/package-lock.json chalk@5.6.1",
            "app/package-lock.json semver@6.3.1",
            "app/package-lock.json string-width@4.2.3",
            "app/yarn.lock @babel/code-frame@7.22.13",
            "app/yarn.lock chalk@2.4.2",
            "app/yarn.lock string-width@4.2.3",
            "lib/pnpm-lock.yaml @ctrl/tinycolor@4.1.1",
            "lib/pnpm-lock.yaml debug@4.4.2",
        ])
        #expect(inventory.notice == "npm package check skipped lockfiles over 30 MB: \(root.path)/huge/package-lock.json.")
    }

    @Test func readsGlobalPackagesWithScopesAndNestingAndSkipsLinksAndBadManifests() throws {
        defer { try? FileManager.default.removeItem(at: root) }
        let modules = "global/lib/node_modules"
        try write(manifest("npm", "10.8.2"), to: "\(modules)/npm/package.json")
        try write(manifest("debug", "4.4.2"), to: "\(modules)/npm/node_modules/debug/package.json")
        try write(manifest("@scope/tool", "1.0.0"), to: "\(modules)/@scope/tool/package.json")
        try write(manifest("@inner/x", "2.0.0"), to: "\(modules)/@scope/tool/node_modules/@inner/x/package.json")
        try write(manifest("bin-thing", "1.0.0"), to: "\(modules)/.bin/package.json")
        try write("{}", to: "\(modules)/.package-lock.json")
        try write("not json", to: "\(modules)/broken/package.json")
        try write(manifest("Bad", "1.0.0"), to: "\(modules)/bad-name/package.json")
        try write(manifest("linked", "1.0.0"), to: "elsewhere/linked/package.json")
        try FileManager.default.createSymbolicLink(atPath: root.appending(path: "\(modules)/linked").path, withDestinationPath: root.appending(path: "elsewhere/linked").path)
        try FileManager.default.createDirectory(at: root.appending(path: "\(modules)/symlinked-manifest"), withIntermediateDirectories: true)
        try FileManager.default.createSymbolicLink(atPath: root.appending(path: "\(modules)/symlinked-manifest/package.json").path, withDestinationPath: root.appending(path: "elsewhere/linked/package.json").path)

        let inventory = NpmInventory.packages(inProjects: [], moduleDirectories: [root.appending(path: modules).path, root.appending(path: "missing").path])

        let summary = inventory.packages.map { "\($0.path.replacingOccurrences(of: root.path + "/\(modules)/", with: "")) \($0.name)@\($0.version)" }
        #expect(summary == [
            "@scope/tool @scope/tool@1.0.0",
            "@scope/tool/node_modules/@inner/x @inner/x@2.0.0",
            "npm npm@10.8.2",
            "npm/node_modules/debug debug@4.4.2",
        ])
        #expect(inventory.notice == nil)
    }

    @Test func globalBudgetCutsTheWalkAndReportsIt() throws {
        defer { try? FileManager.default.removeItem(at: root) }
        for name in ["a", "b", "c"] {
            try write(manifest(name, "1.0.0"), to: "lib/node_modules/\(name)/package.json")
        }
        let modules = root.appending(path: "lib/node_modules").path

        let inventory = NpmInventory.packages(inProjects: [], moduleDirectories: [modules], globalBudget: 2)

        #expect(inventory.packages.map(\.name) == ["a", "b"])
        #expect(inventory.notice == "npm package check covered only the first 2 global packages and skipped the rest of \(modules).")
        #expect(NpmInventory.packages(inProjects: [], moduleDirectories: [modules], globalBudget: 3).notice == nil)
    }

