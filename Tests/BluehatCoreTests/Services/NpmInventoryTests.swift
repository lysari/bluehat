    func valid(_ packages: [(name: String, version: String)]) -> [String] {
        Set(packages.compactMap { InstalledPackage(name: $0.name, version: $0.version, path: "/") }.map { "\($0.name)@\($0.version)" }).sorted()
    }

    func write(_ text: String, to relativePath: String) throws {
        let url = root.appending(path: relativePath)
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try Data(text.utf8).write(to: url)
    }

    func manifest(_ name: String, _ version: String) -> String {
        #"{"name": "\#(name)", "version": "\#(version)", "scripts": {"postinstall": "node evil.js"}}"#
    }

    func rule(_ id: String, _ packages: [MaliciousPackage]) -> Rule {
        Rule(id: id, title: id, severity: .critical, category: .malware, check: .npmPackage, patterns: nil, paths: nil, ports: nil, hashes: nil, setting: nil, product: nil, advisory: nil, ranges: nil, packages: packages, files: nil, teams: nil, bundles: nil, minimumVersion: nil, hosts: nil, summary: nil, remedy: nil, references: nil)
    }

